"""Exact symbolic verification of C128 section 4's algebraic lemma.

Independent of the numerical Gauss-Newton root-find: this is a Groebner-basis
ideal-membership computation over Q, not a floating-point search.

LEMMA.  Let c be a real 3x3 matrix satisfying, for all i,j,m,

    -eps_{abm} c_{ai} c_{bj}  =  eps_{ijk} c_{mk}          (E)

Then  c^T c = -det(c) I,  and the only real solutions are c = 0 and
c in O(3)^- (orthogonal with det = -1).

Checked here in three exact steps:
  (1) every entry of  c^T c + det(c) I  lies in the ideal generated by (E)
      -- i.e. (E) IMPLIES c^T c = -det(c) I, over Q, with no case analysis;
  (2) the scalar consequence: c^T c = mu I with mu = -det(c) forces mu in {0,1}
      and det(c) in {0,-1};
  (3) sanity: c = -R for any R in SO(3) satisfies (E); c = +R for R in SO(3)
      with R != 0 does NOT (checked on a symbolic rotation and on +I).
"""

import sympy as sp

eps = [[[sp.Rational(0)] * 3 for _ in range(3)] for _ in range(3)]
for i, j, k in [(0, 1, 2), (1, 2, 0), (2, 0, 1)]:
    eps[i][j][k] = sp.Integer(1)
    eps[j][i][k] = sp.Integer(-1)

cs = sp.symbols("c0:9", real=True)
C = sp.Matrix(3, 3, cs)


def eqs(mat):
    out = []
    for i in range(3):
        for j in range(3):
            for m in range(3):
                lhs = -sum(
                    eps[a][b][m] * mat[a, i] * mat[b, j]
                    for a in range(3)
                    for b in range(3)
                )
                rhs = sum(eps[i][j][k] * mat[m, k] for k in range(3))
                out.append(sp.expand(lhs - rhs))
    return out


E = [e for e in eqs(C) if e != 0]
print(f"step 0: {len(E)} nontrivial generators of the ideal (E)")

# ---- step 1: ideal membership of  c^T c + det(c) I  ------------------------
target = sp.expand(C.T * C + sp.det(C) * sp.eye(3))
G = sp.groebner(E, *cs, order="grevlex")
print("step 1: reducing each entry of  c^T c + det(c) I  modulo <E>")
all_in = True
for a in range(3):
    for b in range(3):
        rem = G.reduce(sp.expand(target[a, b]))[1]
        ok = sp.simplify(rem) == 0
        all_in = all_in and ok
        print(f"   entry ({a},{b}) reduces to 0 : {ok}")
print(f"step 1 RESULT: (E) => c^T c = -det(c) I  :  {all_in}")

# negative control: something that should NOT be in the ideal
ctrl = G.reduce(sp.expand((C.T * C - sp.det(C) * sp.eye(3))[0, 0]))[1]
print(
    f"step 1 CONTROL: c^T c - det(c) I entry (0,0) reduces to 0 : "
    f"{sp.simplify(ctrl) == 0}   (must be False)"
)

# ---- step 2: the scalar consequence ---------------------------------------
mu = sp.symbols("mu", positive=True)
# c^T c = mu I  =>  det(c)^2 = mu^3 ; and mu = -det(c)  =>  det(c) = -mu
sol = sp.solve([sp.Eq(mu**3, (-mu) ** 2)], mu, dict=True)
print(f"step 2: mu>0 with det^2 = mu^3 and det = -mu  =>  mu in {sol}")
print("        so mu = 1, det(c) = -1, c in O(3)^-   (mu = 0 is the c = 0 root)")

# ---- step 3: sanity checks -------------------------------------------------
th = sp.symbols("theta", real=True)
Rz = sp.Matrix([[sp.cos(th), -sp.sin(th), 0], [sp.sin(th), sp.cos(th), 0], [0, 0, 1]])
res_minus = [sp.simplify(e) for e in eqs(-Rz)]
res_plus = [sp.simplify(e) for e in eqs(Rz)]
print(
    f"step 3: c = -R_z(theta) satisfies (E) identically : {all(e == 0 for e in res_minus)}"
)
print(
    f"step 3: c = +R_z(theta) satisfies (E) identically : "
    f"{all(e == 0 for e in res_plus)}   (must be False)"
)
print(f"step 3: residual norm at c = +I : {sp.sqrt(sum(e**2 for e in eqs(sp.eye(3))))}")
print(
    f"step 3: residual norm at c = -I : {sp.sqrt(sum(e**2 for e in eqs(-sp.eye(3))))}"
)

# a det=-1 orthogonal that is not -R_z: diag(1,1,-1)
D = sp.diag(1, 1, -1)
print(f"step 3: c = diag(1,1,-1) satisfies (E) : {all(e == 0 for e in eqs(D))}")
# and a det=+1 orthogonal that is not +R_z
D2 = sp.diag(1, -1, -1)
print(
    f"step 3: c = diag(1,-1,-1) (det=+1) satisfies (E) : "
    f"{all(e == 0 for e in eqs(D2))}   (must be False)"
)
