print(f"    W1f: the argument applies to T4 and NOT to T7 -- it discriminates: {w1f}")
results["w1f_T7_has_offdiagonal"] = bool(has_swap)
results["w1f_T4_has_offdiagonal"] = bool(t4_has_swap)
results["w1f_discriminates"] = bool(w1f)

# --- CONTROL: does the machinery reproduce C48's factorizing no-go? ----------
print("\nCONTROL -- reproduce C48 under ANSATZ J1 with this code (must still FAIL)")
KS = {"diag(1,1)": I2, "diag(1,i)": np.diag([1, 1j]), "s1": S1, "s2": S2, "s3": S3}
