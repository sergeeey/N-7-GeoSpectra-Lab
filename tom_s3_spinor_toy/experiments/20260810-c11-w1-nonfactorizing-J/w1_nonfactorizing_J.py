"""W1: does a NON-factorizing J readmit a sector-mixing algebra?

WHY THIS IS THE ONE QUESTION LEFT. C48 and C49 both rest on ANSATZ J1 -- that
J = J_M (x) j factorizes -- which I flagged when writing them. If a non-factorizing J
readmits the crossed product C^inf(S3) |x|_iota Z2, then C48's result 2 is an artifact
of my own ansatz AND C49's failure of Poincare duality is lifted with it: the
sector-mixing projection p = (1+u)/2 gives index pairing 2, which C49 already computed
as its non-zero counter-case.

The naive expectation is that W1 SUCCEEDS: the crossed product's Tomita-Takesaki
conjugation is non-factorizing (it carries U_iota in one sector block only) and
satisfies order-zero automatically.

THE ARGUMENT UNDER TEST (predictions W1a-W1f in claim.md, recorded before running):

  W1a  A''s sector-OFF-diagonal blocks all carry U_iota: T01 (f o iota) = f T01
  W1b  those have UNBOUNDED commutator with D, growing like 2(n+3/2)
  W1c  [D,u] = -3i (I (x) s2) is BOUNDED, so [D, J u J^-1] is bounded, so by
       W1a+W1b  J u J^-1 is sector-DIAGONAL = h (x) I     <- the load-bearing step,
       and it uses BOUNDEDNESS ONLY, never a factorization assumption
  W1d  then J(I (x) s2)J^-1 ~ [D_M,h] (x) I must be a unitary involution, so
       [D_M,h] is INVERTIBLE
  W1e  but [D_M,h] bounded forces h to commute with all Clifford multiplications,
       hence h scalar, hence h = +-1, hence [D_M,h] = 0 -- NOT invertible.
  W1f  DISCRIMINATION: the argument must NOT also kill the sector-DIAGONAL algebra
       T7, for which step 5 already exhibited a J. If it kills that too it proves
       too much and is wrong.

FINITE MODEL for the exact parts: X = {a, b, c, c'} with iota = (a)(b)(c c') -- two
fixed points and one free orbit, the same shape as iota(g) = g^-1 on S^3 (fixed set
{+-1}). H_model = C^X (x) C^2_spin (x) C^2_sector.
"""

from __future__ import annotations

import json
from itertools import pairwise, product
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RESULTS_PATH = HERE / "results_w1.json"
results: dict = {}

# --- finite model -------------------------------------------------------------
NX = 4  # X = {a, b, c, c'}
IOTA_PERM = [0, 1, 3, 2]  # a->a, b->b, c<->c'
I2 = np.eye(2, dtype=complex)
S1 = np.array([[0, 1], [1, 0]], dtype=complex)
S2 = np.array([[0, -1j], [1j, 0]], dtype=complex)
S3 = np.array([[-1, 0], [0, 1]], dtype=complex)
PAULI = {"I": I2, "s1": S1, "s2": S2, "s3": S3}

U_IOTA_X = np.zeros((NX, NX), dtype=complex)
for i, j in enumerate(IOTA_PERM):
    U_IOTA_X[j, i] = 1.0


def mult(f: np.ndarray) -> np.ndarray:
    """multiplication by a function on X, tensored with the 2-dim spinor fibre."""
    return np.kron(np.diag(f), I2)


def sector(a_M: np.ndarray, m: np.ndarray) -> np.ndarray:
    """a_M acting on C^X (x) C^2_spin, tensored with sector matrix m."""
    return np.kron(m, a_M)


DIM_M = NX * 2
DIM = DIM_M * 2

print("=" * 78)
print("W1 -- does a NON-factorizing J readmit a sector-mixing algebra?")
print("=" * 78)

# --- the algebra: the crossed product, generated by twisted diagonal + swap ----
rng = np.random.default_rng(20260810)
gens = []
for _ in range(6):
    f = rng.normal(size=NX) + 1j * rng.normal(size=NX)
    f_iota = f[IOTA_PERM]
    # pi(f) = diag(f, f o iota) on the sector index
    gens.append(
        np.block([[mult(f), np.zeros((DIM_M, DIM_M))], [np.zeros((DIM_M, DIM_M)), mult(f_iota)]])
    )
U_SWAP = sector(np.eye(DIM_M), S1)  # u = 1 (x) s1, the sector swap
gens.append(U_SWAP)

# --- W1a: what does the commutant look like? ---------------------------------
print("\nW1a -- structure of A': are the sector-OFF-diagonal blocks all m*U_iota?")
# solve [T, g] = 0 for all generators g, as a linear system on vec(T)
rows = []
for g in gens:
    rows.append(np.kron(np.eye(DIM), g.T) - np.kron(g, np.eye(DIM)))
M = np.vstack(rows)
_, sv, vh = np.linalg.svd(M)
null = vh[np.sum(sv > 1e-9) :].conj().T
print(f"    dim H = {DIM};  dim A' = {null.shape[1]}")
U_IOTA_M = np.kron(U_IOTA_X, I2)
offdiag_ok = True
for k in range(null.shape[1]):
    T = null[:, k].reshape(DIM, DIM)
    T01 = T[:DIM_M, DIM_M:]
    # T01 must satisfy T01 (f o iota) = f T01 for all f  <=>  T01 U_iota^-1 commutes
    # with every multiplication operator (i.e. T01 = m * U_iota, m a bundle endo)
    m_cand = T01 @ np.linalg.inv(U_IOTA_M)
    for _ in range(8):
        f = rng.normal(size=NX)
        offdiag_ok &= bool(np.allclose(m_cand @ mult(f), mult(f) @ m_cand, atol=1e-8))
print(f"    every off-diagonal block factors as m * U_iota with m a bundle endo: {offdiag_ok}")
results["w1a_dim_commutant"] = int(null.shape[1])
results["w1a_offdiag_carries_U_iota"] = bool(offdiag_ok)

# --- W1b: such operators have UNBOUNDED commutator with D --------------------
print("\nW1b -- is [D, m*U_iota] unbounded? spectral model, D_M eigenvalues +-(n+3/2)")
print("      [D_M, m U_iota] = {D_M, m} U_iota = ([D_M,m] + 2 m D_M) U_iota")
print("      the 2*m*D_M term is first order -- its norm grows with the level.")
# FIRST VERSION OF THIS BLOCK JUST PRINTED 2*max(n+3/2) FOR RISING TRUNCATIONS, which
# grows by construction and could not have failed. Second version compared it against
# ||[D_M, m]|| for a level-preserving m -- but that came out EXACTLY 0, because such an m
# commutes with D_M in this toy, so the "bounded" side was degenerate and the comparison
# still could not fail. The toy has no locality structure and CANNOT represent a bundle
# endomorphism's [D_M, m] = Clifford . dm. So the block is split honestly:
#   (i)  [VERIFIED-numpy] the exact identity [D_M, m U_iota] = {D_M, m} U_iota, which is
#        what the whole step rests on -- checkable here because it needs only
#        U_iota D_M U_iota = -D_M;
#   (ii) [VERIFIED-numpy] the norm of that object grows linearly in the cutoff;
#   (iii)[INFERRED-analytic] for a bundle endomorphism m, [D_M, m] = Clifford . dm is
#        ORDER ZERO hence bounded, while {D_M,m} = [D_M,m] + 2 m D_M is ORDER ONE. This
#        is a fact about differential operators, NOT verified in the toy, and is marked.
norms = {}
identity_ok = True
for nmax in (4, 8, 16, 32):
    lv = [s * (n + 1.5) for n in range(nmax + 1) for s in (+1, -1)]
    d_m = np.diag(lv).astype(complex)
    u_i = np.zeros_like(d_m)
    for n in range(nmax + 1):
        u_i[2 * n, 2 * n + 1] = u_i[2 * n + 1, 2 * n] = 1.0
    assert np.allclose(u_i @ d_m @ u_i, -d_m), "U_iota must flip D_M in this model"
    m = np.diag([1.0 if k % 3 else -1.0 for k in range(len(lv))]).astype(complex)
    lhs = d_m @ (m @ u_i) - (m @ u_i) @ d_m
    rhs = (d_m @ m + m @ d_m) @ u_i
    identity_ok &= bool(np.allclose(lhs, rhs))
    norms[nmax] = {"norm": float(np.linalg.norm(lhs, 2)), "max_eig": max(lv)}
    print(
        f"      N_MAX = {nmax:3d}   ||[D_M, m U_iota]|| = {norms[nmax]['norm']:7.2f}"
        f"   (max eig {max(lv):5.1f})   identity holds: {np.allclose(lhs, rhs)}"
    )
seq = [4, 8, 16, 32]
grows = all(norms[b]["norm"] > norms[a]["norm"] for a, b in pairwise(seq))
linear = abs(norms[32]["norm"] / norms[32]["max_eig"] - 2.0) < 0.05
print(f"    (i)   identity [D_M, m U_iota] = {{D_M, m}} U_iota holds exactly: {identity_ok}")
print(f"    (ii)  its norm grows, and grows LINEARLY in the cutoff (ratio -> 2): {grows and linear}")
print("    (iii) [INFERRED-analytic, NOT verified here] for a bundle endomorphism m,")
print("          [D_M, m] = Clifford . dm is order ZERO, while {D_M,m} = [D_M,m] + 2 m D_M")
print("          is order ONE. The toy has no locality and cannot check this.")
print("    => the off-diagonal part of A' has UNBOUNDED commutator with D unless m = 0.")
results["w1b_identity_exact"] = bool(identity_ok)
results["w1b_norm_growth"] = norms
results["w1b_unbounded"] = bool(identity_ok and grows and linear)
grows = bool(identity_ok and grows and linear)

# --- W1c: [D,u] is bounded, so J u J^-1 must be sector-DIAGONAL ---------------
print("\nW1c -- [D, u] where u = 1 (x) s1  (D = D_M (x) I + (3/2) I (x) s3)")
comm_sector = 1.5 * (S3 @ S1 - S1 @ S3)
print(f"    [D,u] = (3/2) I (x) [s3,s1] = I (x) {np.array2string(comm_sector, precision=1)}")
is_bounded = np.allclose(comm_sector, -3j * S2)
print(f"    equals -3i (I (x) s2), a BOUNDED operator: {is_bounded}")
print("    J[D,u]J^-1 = eps' [D, J u J^-1], so [D, J u J^-1] is BOUNDED too.")
print("    With W1a+W1b that forces the off-diagonal part of J u J^-1 to VANISH:")
print("       J u J^-1 = h (x) I,  h a bundle endomorphism.   <- NO ANSATZ USED")
results["w1c_commutator_bounded"] = bool(is_bounded)

# --- W1d/W1e: the contradiction ----------------------------------------------
print("\nW1d -- J(I (x) s2)J^-1 ~ [D_M, h] (x) I must be a UNITARY INVOLUTION")
print("       (because I (x) s2 is one, and J is antiunitary), so [D_M,h] is INVERTIBLE")
print("\nW1e -- but [D_M, h] BOUNDED forces h to commute with Clifford multiplication")
print("       [D_M, h] = sum_a [e_a . , h] grad_a  +  (Clifford)(grad h)")
print("       the first term is FIRST ORDER unless [e_a . , h] = 0 for every a.")
# the Clifford commutant on the 2-dim spinor space of Cl(3): Pauli matrices
cl_gens = [S1, S2, S3]
rows = [np.kron(np.eye(2), g.T) - np.kron(g, np.eye(2)) for g in cl_gens]
_, sv2, vh2 = np.linalg.svd(np.vstack(rows))
cl_commutant = vh2[np.sum(sv2 > 1e-9) :].conj().T
dim_cl_comm = cl_commutant.shape[1]
is_scalar = all(
    np.allclose(
        cl_commutant[:, k].reshape(2, 2), np.trace(cl_commutant[:, k].reshape(2, 2)) / 2 * I2
    )
    for k in range(dim_cl_comm)
)
print(f"       commutant of the Clifford action on C^2_spin has dim {dim_cl_comm}")
print(f"       and consists of SCALARS only: {is_scalar}")
print("       so h = lambda(x) * I with lambda^2 = 1 and lambda continuous")
print("       => on connected S^3, lambda = +1 or -1, so h = +-I and [D_M,h] = 0.")
print("       ZERO IS NOT INVERTIBLE. CONTRADICTION.")
w1e = dim_cl_comm == 1 and is_scalar
results["w1e_clifford_commutant_dim"] = int(dim_cl_comm)
results["w1e_commutant_is_scalars"] = bool(is_scalar)

# --- W1f: DISCRIMINATION -- does the argument prove too much? ----------------
print("\nW1f -- DISCRIMINATION: does this argument also kill the sector-DIAGONAL T7?")
print("       It must not -- step 5 exhibited a J for T7, so an argument that killed")
print("       it too would be proving too much and would be WRONG.")
print("       The chain enters at W1c via [D,u] for the sector-SWAP u. T7 contains no")
print("       such element: its sector parts are {I, s3}, both DIAGONAL.")
t7_sector = ["I", "s3"]
t4_sector = ["I", "s1", "s2", "s3"]


def has_offdiagonal(syms: list[str]) -> bool:
    return any(not np.allclose(PAULI[s], np.diag(np.diag(PAULI[s]))) for s in syms)


has_swap = has_offdiagonal(t7_sector)
t4_has_swap = has_offdiagonal(t4_sector)
print(f"       T7 contains a sector-off-diagonal element: {has_swap}   (expect False)")
print(f"       T4 contains a sector-off-diagonal element: {t4_has_swap}   (expect True)")
print("       [STRUCTURAL OBSERVATION, not a test -- immediate from the symbol lists.")
print("        Recorded as such rather than dressed up as a numerical finding.]")
