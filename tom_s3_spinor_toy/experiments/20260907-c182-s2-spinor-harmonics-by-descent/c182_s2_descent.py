# Spin-weight decomposition of H_k
# ---------------------------------------------------------------------------
def weight_spectrum(k: int, R: list[np.ndarray]) -> dict:
    """Diagonalise the U(1) generator X_3^R on H_k. Normalisation: C180's
    fields obey [X_a, X_b] = -2 eps_abc X_c, i.e. they are TWICE the
    standard so(3) generators, so the standard weight is m' = eigenvalue
    of (-i/2) X_3^R. The normalisation is not assumed -- it is checked
    against the ladder structure (equally spaced, step 1, symmetric)."""
    basis = C180.harmonic_basis(k)
    x3 = C180.vector_field_matrix(R[2], k, basis)
    evals = np.linalg.eigvals(-0.5j * x3.astype(complex))
    max_imag = float(np.max(np.abs(evals.imag)))
    real_ev = np.sort(evals.real)

    clusters: list[list[float]] = []
    for e in real_ev:
        if clusters and abs(e - clusters[-1][0]) < 1e-6:
            clusters[-1].append(float(e))
        else:
            clusters.append([float(e)])
    weights = [{"weight": round(c[0], 6), "multiplicity": len(c)} for c in clusters]

    values = [w["weight"] for w in weights]
    mults = [w["multiplicity"] for w in weights]
    expected_values = [(-k / 2.0) + i for i in range(k + 1)]
    ladder_ok = len(values) == k + 1 and all(
        abs(v - e) < 1e-6 for v, e in zip(values, expected_values)
    )
    mults_uniform = all(m == k + 1 for m in mults)

    return {
        "k": k,
        "dim_H_k": basis.shape[1],
        "weights_real": max_imag < 1e-9,
        "weight_spectrum": weights,
        "weights_form_expected_ladder": bool(ladder_ok),
        "all_multiplicities_equal_k_plus_1": bool(mults_uniform),
    }


def sector_dimension(spec: dict, target_weight: float) -> int | None:
    for w in spec["weight_spectrum"]:
        if abs(w["weight"] - target_weight) < 1e-6:
            return int(w["multiplicity"])
    return None


def scalar_control(specs: list[dict]) -> dict:
    """The weight-0 sector for k even has dimension 2l+1 with l=k/2 -- the
    ordinary scalar spherical-harmonic count on S^2.

    CORRECTED after a context-blind skeptic pass: an earlier version of
    this docstring called this 'the stronger of the two checks'. That is
    FALSE. 2l+1 (k even) and 2(l+1) (k odd) are BOTH identically k+1, and
    `ladder_ok` already asserts every sector has multiplicity k+1 -- so
    this is not an independent confirmation of anything, it is the same
    algebraic identity restated. Kept because the numbers are still worth
    displaying, but it carries no evidential weight beyond the ladder.
    The genuinely independent check is fibre_invariance_check()."""
    rows = []
    ok = True
    for spec in specs:
        k = spec["k"]
        if k % 2 != 0:
            continue
        ell = k // 2
        found = sector_dimension(spec, 0.0)
        expected = 2 * ell + 1
        match = found == expected
        ok = ok and match
        rows.append(
            {
                "k": k,
                "l": ell,
                "weight_0_dimension_found": found,
                "expected_2l_plus_1": expected,
                "match": bool(match),
            }
        )
    return {"per_level": rows, "all_match": bool(ok)}


def spinor_sectors(specs: list[dict]) -> dict:
    """THE DELIVERABLE: the weight-+-1/2 sectors are the two-component S^2
    spinor harmonics. They must exist exactly for k ODD, with dimension
    k+1 = 2(l+1), l=(k-1)/2 -- the standard S^2 Dirac multiplicity."""
    rows = []
    ok = True
    parity_ok = True
    for spec in specs:
        k = spec["k"]
        dim_plus = sector_dimension(spec, 0.5)
        dim_minus = sector_dimension(spec, -0.5)
        if k % 2 == 0:
            # half-integer weights must NOT exist at even k
            exists = dim_plus is not None or dim_minus is not None
            parity_ok = parity_ok and not exists
            rows.append(
                {
                    "k": k,
                    "parity": "even",
                    "half_integer_weight_present": bool(exists),
                    "expected_present": False,
                }
            )
            continue
        ell = (k - 1) // 2
        expected = 2 * (ell + 1)
        match = dim_plus == expected and dim_minus == expected
        ok = ok and match
        rows.append(
            {
                "k": k,
                "parity": "odd",
                "l": ell,
                "dim_weight_plus_half": dim_plus,
                "dim_weight_minus_half": dim_minus,
                "expected_2_l_plus_1": expected,
                "match": bool(match),
            }
        )
    return {
        "per_level": rows,
        "all_match": bool(ok),
        "half_integer_weights_only_at_odd_k": bool(parity_ok),
    }


def fibre_invariance_check(R: list[np.ndarray]) -> dict:
    """REPLACES a tautological check the first version of this round shipped.

    The original `nogo_still_respected()` tested `|w| ~ 0.5 AND |w| < 1e-9`
    -- a logically impossible conjunction, so its offender list was empty
    for ANY input and the check could not fail. A context-blind skeptic
    caught it. What it was trying to say is real, so it is done properly
    here, on the actual group action rather than on the weight labels:

    the U(1) fibre acts by q -> q*exp(theta*e_3), i.e. on H_k by
    U(theta) = exp(theta * X_3^R). A WEIGHT-0 vector must be fixed by
    U(theta) for EVERY theta (that is what "descends to a function on S^2"
    means). A WEIGHT-1/2 vector must NOT be -- and specifically must pick
    up exactly -1 at theta = pi, the half-turn.

    Both halves can genuinely fail, which the previous version could not."""
    rows = []
    all_ok = True
    for k in (2, 3):  # one even (weight 0 exists), one odd (weight 1/2 exists)
        basis = C180.harmonic_basis(k)
        x3 = C180.vector_field_matrix(R[2], k, basis).astype(complex)
        evals, evecs = np.linalg.eig(-0.5j * x3)

        def u_of(theta: float, gen: np.ndarray = x3) -> np.ndarray:
            w, v = np.linalg.eig(theta * gen)
            return v @ np.diag(np.exp(w)) @ np.linalg.inv(v)

        for target, label in ((0.0, "weight_0"), (0.5, "weight_half")):
            idx = [i for i in range(len(evals)) if abs(evals[i].real - target) < 1e-6]
            if not idx:
                continue
            vec = evecs[:, idx[0]]
            vec = vec / np.linalg.norm(vec)

            # invariance under a generic theta, and the half-turn phase
            v_generic = u_of(0.7) @ vec
            drift_generic = float(np.linalg.norm(v_generic - vec))
            v_half = u_of(np.pi) @ vec
            phase_half = complex(np.vdot(vec, v_half))

            if target == 0.0:
                ok = drift_generic < 1e-9 and abs(phase_half - 1.0) < 1e-9
            else:
                ok = drift_generic > 1e-3 and abs(phase_half + 1.0) < 1e-6
            all_ok = all_ok and ok
            rows.append(
                {
                    "k": k,
                    "sector": label,
                    "drift_under_generic_rotation": drift_generic,
                    "phase_after_half_turn": [
                        round(phase_half.real, 9),
                        round(phase_half.imag, 9),
                    ],
                    "expected": ("invariant, phase +1" if target == 0.0 else "moves, phase -1"),
                    "ok": bool(ok),
                }
            )
    return {
        "per_sector": rows,
        "weight0_descends_and_half_does_not": bool(all_ok),
    }


