"""C182: S^2 spinor harmonics by descent from S^3, via the Hopf fibration.

C179 showed a spinor multiplet of ordinary functions cannot exist on S^2
(or S^3) and recommended INVERTING Tom Lawrence's proposed order: get S^2
from S^3, not the other way round. This round tests that recommendation.

Method: S^2 = S^3 / U(1), where the U(1) sits inside SU(2)_R and is
generated by X_3^R. Decomposing H_k (the degree-k harmonic polynomials on
S^3) into eigenspaces of X_3^R decomposes L^2(S^3) by SPIN WEIGHT:

  weight  0    -> ordinary functions on S^2   (scalar spherical harmonics)
  weight +-1/2 -> two-component SPINOR sections on S^2

Predictions, pre-registered in claim.md:
  * weight 0    exists for k even, dimension k+1 = 2l+1   (l = k/2)
  * weight +-1/2 exists for k odd,  dimension k+1 = 2(l+1) (l = (k-1)/2)

Reuses C180's harmonic_basis / vector_field_matrix unmodified.
"""

