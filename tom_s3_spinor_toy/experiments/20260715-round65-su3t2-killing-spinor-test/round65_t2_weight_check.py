r"""
Round 65 -- SU(3)/T^2 Killing-spinor trivial-block rank test.

Re-derives (does NOT copy-paste from Round 59's S^6=G_2/SU(3) computation)
whether the "Term2-analog vanishes" step of Round 59's rank-forcing argument
survives when the isotropy group is the ABELIAN T^2 = U(1) x U(1) instead of
SU(3), for the flag manifold SU(3)/T^2 = F_{1,2,3}
(Charbonneau-Harland 2016, arXiv:1510.07720v2, Section 4, eq. before (35) --
"there are precisely four homogeneous nearly Kahler six-manifolds ...
F_{1,2,3} = SU(3)/U(1)^2").

For an abelian isotropy group every irrep is 1-dimensional, indexed by an
integer weight/charge pair (m1, m2) under the two Cartan generators

    H1 = i*diag(1,-1,0),   H2 = i*diag(0,1,-1)          (CH2016, page 21,
                                                           "The subalgebra h
                                                           is generated by")

"No SU(3) singlet in Lambda^2 (x) Lambda^2 = 3 (x) 3" (Round 59's S^6
argument) becomes, for T^2: "no weight-(0,0) term in the T^2-weight-graded
tensor product Lambda^2(m^{1,0}) (x) Lambda^2(m^{1,0})". This script checks
that condition EXPLICITLY, from CH2016's own stated basis and Cartan
generators -- it does not assume the SU(3) result transfers.

Primary-source inputs (transcribed, cited inline):
  * CH2016 eq. (35) (page 21-22): "A basis for m^{1,0}_C is given by"
        C1 = E_12,  C2 = E_23,  C3 = E_31     (3x3 elementary matrices)
    -- transcribed EXACTLY from the PDF's flattened matrix entries (verified
    below by printing them back out).
  * CH2016 page 21: H1 = i*diag(1,-1,0), H2 = i*diag(0,1,-1).
  * CH2016 page 22 (just before Prop. count of components): states the
    m*_C weight list directly: V(2,-1) + V(-1,2) + V(-1,-1) + V(-2,1)
    + V(1,-2) + V(1,1) -- used here ONLY as an independent cross-check on
    the weights this script computes from the Cartan generators + basis
    matrices, not as an input.
  * CH2016 Section 2 (general, isotropy-independent): nearly-Kahler means a
    real Killing spinor exists with NONZERO Killing constant lambda by
    DEFINITION; Section 4 explicitly lists SU(3)/U(1)^2 as one of the four
    homogeneous nearly Kahler six-manifolds carrying the metric normalised
    "as in Section 2" (i.e. with the same nonzero lambda convention) "in all
    four cases". This is the source for Term1 != 0 -- no separate
    computation needed, see decision.md.

Run:  python round65_t2_weight_check.py
"""

from itertools import combinations, product

# ----------------------------------------------------------------------------
# STEP 0: transcribe CH2016 eq. (35) basis matrices for m^{1,0}_C exactly,
#         and the Cartan generators H1, H2 (as diagonal coefficient lists,
#         dropping the overall "i", since ad(H)(E_ij) = (H_i - H_j) E_ij for
#         diagonal H = i*diag(d1,d2,d3) gives weight m with i*m = i*(d_i-d_j)
#         i.e. m = d_i - d_j directly).
# ----------------------------------------------------------------------------
C1 = [[0, 1, 0], [0, 0, 0], [0, 0, 0]]  # E_12
C2 = [[0, 0, 0], [0, 0, 1], [0, 0, 0]]  # E_23
C3 = [[0, 0, 0], [0, 0, 0], [1, 0, 0]]  # E_31


def matrix_to_ij(M):
    """Read off (i,j) (1-indexed) of the single nonzero entry of an elementary matrix."""
    for r in range(3):
        for c in range(3):
            if M[r][c] != 0:
                return r + 1, c + 1
    raise ValueError("zero matrix")


print("=" * 78)
print("STEP 0  Transcription check: C1,C2,C3 from CH2016 eq.(35)")
print("=" * 78)
for name, M in [("C1", C1), ("C2", C2), ("C3", C3)]:
    i, j = matrix_to_ij(M)
    print(f"  {name} = E_{i}{j}   (matrix {M})")

H1 = (1, -1, 0)  # H1 = i*diag(1,-1,0)   (CH2016 page 21)
H2 = (0, 1, -1)  # H2 = i*diag(0,1,-1)


def weight(i, j):
    """weight (m1,m2) of E_ij under ad(H1),ad(H2):  ad(H)(E_ij) = i*(H_i - H_j) E_ij."""
    m1 = H1[i - 1] - H1[j - 1]
    m2 = H2[i - 1] - H2[j - 1]
    return (m1, m2)


ALL_ROOTS = [(1, 2), (1, 3), (2, 1), (2, 3), (3, 1), (3, 2)]
weights_all = {f"E_{i}{j}": weight(i, j) for (i, j) in ALL_ROOTS}

print()
print("=" * 78)
print("STEP 1  Weights of all 6 root vectors under (H1,H2), cross-checked")
print("        against CH2016's own stated m*_C weight list")
print("=" * 78)
for name, w in weights_all.items():
    print(f"  weight({name}) = {w}")

CH2016_STATED_MSTAR = {(2, -1), (-1, 2), (-1, -1), (-2, 1), (1, -2), (1, 1)}
computed_set = set(weights_all.values())
print()
print(f"  CH2016-stated m*_C weight set : {sorted(CH2016_STATED_MSTAR)}")
print(f"  computed weight set (all 6 E_ij): {sorted(computed_set)}")
match = computed_set == CH2016_STATED_MSTAR
print(f"  match: {match}")
assert match, "Transcription/weight computation does not match CH2016's stated m*_C list"

# ----------------------------------------------------------------------------
# STEP 2: m^{1,0}_C = weights of {C1,C2,C3} = {E12,E23,E31}, per eq.(35).
# ----------------------------------------------------------------------------
W10 = [weights_all["E_12"], weights_all["E_23"], weights_all["E_31"]]
print()
print("=" * 78)
print("STEP 2  m^{1,0}_C = weights of {E12,E23,E31}  (CH2016 eq.35 basis)")
print("=" * 78)
print(f"  W10 = {W10}")
sum10 = tuple(sum(x) for x in zip(*W10))
print(f"  sum(W10) = {sum10}   (must be (0,0) for the top wedge Lambda^3(m^1,0)")
print("             to be T^2-invariant -- forced by det=1, m^{1,0} subset su(3))")
assert sum10 == (0, 0), "Lambda^3(m^{1,0}) is not T^2-invariant -- ILL-POSED trigger"


# ----------------------------------------------------------------------------
# STEP 3: build Lambda^0..3(m^{1,0}) weight multisets, then Sigma_odd/Sigma_even.
# ----------------------------------------------------------------------------
def wsum(ws):
    return tuple(sum(x) for x in zip(*ws)) if ws else (0, 0)


LAM0 = [(0, 0)]
LAM1 = list(W10)
LAM2 = [wsum(pair) for pair in combinations(W10, 2)]
LAM3 = [wsum(W10)]

print()
print("=" * 78)
print("STEP 3  Exterior powers of m^{1,0}_C (weights)")
print("=" * 78)
print(f"  Lambda^0 = {LAM0}")
print(f"  Lambda^1 = {LAM1}")
print(f"  Lambda^2 = {LAM2}")
print(f"  Lambda^3 = {LAM3}")

SIGMA_EVEN = LAM0 + LAM2  # Lambda^0 + Lambda^2, dim 4
SIGMA_ODD = LAM1 + LAM3  # Lambda^1 + Lambda^3, dim 4
print(f"  Sigma_even (Lambda^0+Lambda^2) = {SIGMA_EVEN}   dim={len(SIGMA_EVEN)}")
print(f"  Sigma_odd  (Lambda^1+Lambda^3) = {SIGMA_ODD}    dim={len(SIGMA_ODD)}")
assert len(SIGMA_EVEN) == 4 and len(SIGMA_ODD) == 4


# ----------------------------------------------------------------------------
# STEP 4: domain = T^2-invariants of Sigma_odd (x) Sigma_even (weight-(0,0) pairs)
#         target = T^2-invariants of Sigma_even (x) Sigma_even
# ----------------------------------------------------------------------------
def zero_weight_pairs(A, B):
    return [(a, b) for a, b in product(A, B) if (a[0] + b[0], a[1] + b[1]) == (0, 0)]


domain_pairs = zero_weight_pairs(SIGMA_ODD, SIGMA_EVEN)
target_pairs = zero_weight_pairs(SIGMA_EVEN, SIGMA_EVEN)

print()
print("=" * 78)
print("STEP 4  T^2-invariant (weight-0) subspaces  (analog of Round 59's")
print("        SU(3)-invariant domain/target)")
print("=" * 78)
print("  domain = (Sigma_odd (x) Sigma_even)^(T^2) weight-0 pairs:")
for p in domain_pairs:
    print(f"    {p[0]} (x) {p[1]}")
print(f"  dim(domain) = {len(domain_pairs)}   (Round 59's SU(3) analog had dim 2 --")
print("               a genuine structural difference for abelian isotropy,")
print("               see decision.md)")
print("  target = (Sigma_even (x) Sigma_even)^(T^2) weight-0 pairs:")
for p in target_pairs:
    print(f"    {p[0]} (x) {p[1]}")
print(f"  dim(target) = {len(target_pairs)}   (Round 59's SU(3) analog also had dim 1)")
assert len(target_pairs) == 1, "target dimension != 1, argument structure changes"

# identify v_b = (top wedge of Sigma_odd, weight (0,0)) (x) (Lambda^0 gen of Sigma_even, weight (0,0))
v_b_weight = ((0, 0), (0, 0))
assert v_b_weight in domain_pairs, "v_b analog is not even in the T^2-invariant domain"
print()
print(f"  v_b analog = (top-wedge)(x)(1) has weight {v_b_weight} -- confirmed in domain.")
print("  Since dim(target)=1, ANY nonzero component of D+(v_b) along the target")
print("  forces rank(D+|trivial-block) = 1 (cannot exceed 1, target is 1-dim).")

# ----------------------------------------------------------------------------
# STEP 5: Term2-analog vanishing check.
#   Term2 = sum_i e_i (x) nabla_i acting on v_b = (top wedge)(x)(1).
#   GENERAL Clifford-algebra fact (isotropy-independent, valid for ANY
#   Lagrangian L' of any dimension): Clifford mult of a single generator e_i
#   on the TOP wedge (Lambda^3, here) can only land in Lambda^2 (contraction
#   lowers degree by 1; Lambda^4 = 0 since dim_C L' = 3). So e_i . (top wedge)
#   in Sigma_odd (x) Sigma_even ALWAYS lands in Lambda^2(x)Lambda^2, for any H.
#   The isotropy-DEPENDENT question is whether Lambda^2(x)Lambda^2 contains a
#   weight-(0,0) (T^2-singlet) term -- checked explicitly below, mirroring
#   Round 59's SU(3) rep-theory check "Lambda^2 (x) Lambda^2 = 3 (x) 3 has no
#   SU(3) singlet", but with T^2 weights/charges instead of SU(3) irreps.
# ----------------------------------------------------------------------------
print()
print("=" * 78)
print("STEP 5  Term2-analog vanishing: does Lambda^2(x)Lambda^2 contain a")
print('        T^2-weight-(0,0) ("no singlet" analog) term?')
print("=" * 78)
lam2_pairs_zero = zero_weight_pairs(LAM2, LAM2)
print(f"  Lambda^2 weights: {LAM2}")
print(f"  Lambda^2 (x) Lambda^2 weight-0 pairs found: {lam2_pairs_zero}")
print(f"  count = {len(lam2_pairs_zero)}")
term2_vanishes = len(lam2_pairs_zero) == 0
print(f"  => Term2-analog structurally forced to vanish (no weight-0 term): {term2_vanishes}")

print()
print("=" * 78)
print("SUMMARY")
print("=" * 78)
print(f"  transcription/weight cross-check vs CH2016 stated m*_C list : {match}")
print(f"  Lambda^3(m^1,0) T^2-invariant (top wedge exists)            : {sum10 == (0, 0)}")
print(f"  dim(domain, Sigma_odd(x)Sigma_even)^(T^2)                    : {len(domain_pairs)}")
print(f"  dim(target, Sigma_even(x)Sigma_even)^(T^2)                   : {len(target_pairs)}")
print(
    f"  v_b analog lies in domain                                    : {v_b_weight in domain_pairs}"
)
print(f"  Term2-analog forced to vanish (no weight-0 in Lam2(x)Lam2)   : {term2_vanishes}")
print()
if term2_vanishes and len(target_pairs) == 1:
    print("  VERDICT: PROMOTE-consistent -- Term1 nonzero (general nearly-Kahler")
    print("  Killing-spinor fact, source-stated for SU(3)/U(1)^2 by CH2016 Sec.4,")
    print("  see decision.md) + Term2-analog vanishes by an honestly-rechecked")
    print("  T^2 weight computation (this script) => rank(D+|trivial-block) = 1")
    print("  by the same two-line argument, target space being 1-dimensional.")
else:
    print("  VERDICT: does NOT match the PROMOTE bucket as computed -- see decision.md")
